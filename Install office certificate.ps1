param(
    [switch]$Remove,
    [switch]$ValidateOnly
)

$ErrorActionPreference = 'Stop'
$expectedFingerprint = '__OFFICE_CA_SHA256__'
$certificatePath = Join-Path $PSScriptRoot 'Office Voucher Root CA.cer'
if ($expectedFingerprint -notmatch '^[A-F0-9]{64}$') {
    throw 'This is an unconfigured installer template. Use the ZIP generated by the approved server setup.'
}
$certificate = New-Object Security.Cryptography.X509Certificates.X509Certificate2($certificatePath)
$sha256 = [Security.Cryptography.SHA256]::Create()
try {
    $fingerprint = [BitConverter]::ToString($sha256.ComputeHash($certificate.RawData)).Replace('-', '')
} finally {
    $sha256.Dispose()
}
if ($fingerprint -ne $expectedFingerprint -or $certificate.HasPrivateKey) {
    throw 'Certificate fingerprint mismatch or unexpected private key. Do not install this package.'
}
$constraints = $certificate.Extensions | Where-Object { $_.Oid.Value -eq '2.5.29.19' }
if (-not $constraints -or -not $constraints.CertificateAuthority -or $certificate.Subject -ne $certificate.Issuer) {
    throw 'The package does not contain the expected self-issued public root certificate.'
}
Write-Host "Office root CA SHA-256: $fingerprint"
if ($ValidateOnly) { return }
$storePath = 'Cert:\CurrentUser\Root\' + $certificate.Thumbprint
if ($Remove) {
    if (Test-Path -LiteralPath $storePath) { Remove-Item -LiteralPath $storePath }
    Write-Host 'Office certificate removed for this Windows user. Close and reopen your browser.'
    return
}
if ($certificate.NotAfter -le (Get-Date) -or $certificate.NotBefore -gt (Get-Date)) {
    throw 'The root certificate is outside its validity period. Check the PC clock and contact the administrator.'
}
if (-not (Test-Path -LiteralPath $storePath)) {
    Import-Certificate -FilePath $certificatePath -CertStoreLocation 'Cert:\CurrentUser\Root' | Out-Null
}
Write-Host 'Office certificate installed for this Windows user. Close and reopen Edge or Chrome.'
Write-Host 'Open https://pmo-moz-asststa:8443 (office network or Tailscale required).'
Write-Host 'Each Windows user needs this installation. Browsers with a separate certificate store may need a separate import.'
